using System;
using System.Collections.Generic;
using UnityEngine;

/// <summary>Transfers a newly loaded or created save between the menu and gameplay scene.</summary>
public static class CosmicRaysSession
{
    /// <summary>One-time state that the gameplay scene consumes during startup.</summary>
    public static CosmicRaysSaveData PendingSave { get; private set; }
    /// <summary>Optional message to display after the pending save is applied.</summary>
    public static string Notice { get; private set; }

    /// <summary>Sets the save state and optional notice for the next gameplay scene.</summary>
    public static void SetPendingSave(CosmicRaysSaveData data, string notice)
    {
        string validationError;
        if (!CosmicRaysSaveSystem.ValidateData(data, out validationError))
        {
            throw new ArgumentException("Cannot queue invalid mission data. " + validationError, nameof(data));
        }
        PendingSave = data;
        Notice = notice;
    }

    /// <summary>Returns and clears the pending save snapshot.</summary>
    public static CosmicRaysSaveData TakePendingSave()
    {
        CosmicRaysSaveData data = PendingSave;
        PendingSave = null;
        return data;
    }

    /// <summary>Clears the current session notice after it has been shown.</summary>
    public static void ClearNotice()
    {
        Notice = null;
    }

    /// <summary>Creates a new mission snapshot using configured starting values and supplies.</summary>
    public static CosmicRaysSaveData CreateNewGame(SurvivalConfig config)
    {
        if (config == null)
        {
            throw new ArgumentNullException(nameof(config));
        }

        string validationError;
        if (!config.Validate(out validationError))
        {
            throw new ArgumentException(validationError, nameof(config));
        }

        var data = new CosmicRaysSaveData();
        data.resources = new ResourceSnapshot
        {
            oxygen = config.startingOxygen,
            water = config.startingWater,
            energy = config.startingEnergy
        };
        data.inventory = new List<InventoryStackData>();
        data.completedObjectiveIds = new List<string>();

        if (config.startingInventory != null)
        {
            var quantities = new Dictionary<string, int>(StringComparer.Ordinal);
            for (int i = 0; i < config.startingInventory.Length; i++)
            {
                StartingInventoryItem item = config.startingInventory[i];
                if (item != null && !string.IsNullOrWhiteSpace(item.itemId) && item.quantity > 0)
                {
                    int existing;
                    quantities.TryGetValue(item.itemId, out existing);
                    quantities[item.itemId] = (int)Math.Min(int.MaxValue, (long)existing + item.quantity);
                }
            }

            var itemIds = new List<string>(quantities.Keys);
            itemIds.Sort(StringComparer.Ordinal);
            for (int i = 0; i < itemIds.Count; i++)
            {
                data.inventory.Add(new InventoryStackData
                {
                    itemId = itemIds[i],
                    quantity = quantities[itemIds[i]]
                });
            }
        }
        return data;
    }
}

/// <summary>Loads shared ScriptableObject definitions from the Resources folders generated by setup.</summary>
public static class CosmicRaysRuntimeContent
{
    /// <summary>Loads the survival configuration, or returns null after logging a missing-asset error.</summary>
    public static SurvivalConfig LoadSurvivalConfig()
    {
        SurvivalConfig config = Resources.Load<SurvivalConfig>("CosmicRays/Data/SurvivalConfig");
        if (config != null)
        {
            return config;
        }

        Debug.LogError("SurvivalConfig asset is missing. Run Tools/COSMIC RAYS/Setup Scenes and Data in the Unity Editor.");
        return null;
    }

    /// <summary>Loads all inventory item definitions from Resources/CosmicRays/Items.</summary>
    public static List<InventoryItemDefinition> LoadItems()
    {
        InventoryItemDefinition[] assets =
            Resources.LoadAll<InventoryItemDefinition>("CosmicRays/Items");
        if (assets.Length == 0)
        {
            Debug.LogError("No inventory item definitions were found in Resources/CosmicRays/Items.");
        }
        return new List<InventoryItemDefinition>(assets);
    }

    /// <summary>Loads all mission objective definitions from Resources/CosmicRays/Objectives.</summary>
    public static List<MissionObjectiveDefinition> LoadObjectives()
    {
        MissionObjectiveDefinition[] assets =
            Resources.LoadAll<MissionObjectiveDefinition>("CosmicRays/Objectives");
        if (assets.Length == 0)
        {
            Debug.LogError("No mission objectives were found in Resources/CosmicRays/Objectives.");
        }
        return new List<MissionObjectiveDefinition>(assets);
    }
}
